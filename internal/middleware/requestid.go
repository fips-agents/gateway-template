package middleware

import (
	"crypto/rand"
	"fmt"
	"net/http"
)

// RequestID is middleware that ensures every request has an X-Request-ID header.
// If the inbound request carries one, it is preserved; otherwise a UUID v4 is
// generated. The request ID is set on both the request (for downstream handlers
// and middleware) and the response (for client correlation).
func RequestID(next http.Handler) http.Handler {
	return http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		id := r.Header.Get("X-Request-ID")
		if id == "" {
			id = newUUID()
			r.Header.Set("X-Request-ID", id)
		}
		w.Header().Set("X-Request-ID", id)
		next.ServeHTTP(w, r)
	})
}

// newUUID generates a version 4 (random) UUID using crypto/rand.
func newUUID() string {
	var b [16]byte
	_, _ = rand.Read(b[:])
	b[6] = (b[6] & 0x0f) | 0x40 // version 4
	b[8] = (b[8] & 0x3f) | 0x80 // variant 10
	return fmt.Sprintf("%08x-%04x-%04x-%04x-%012x",
		b[0:4], b[4:6], b[6:8], b[8:10], b[10:16])
}
